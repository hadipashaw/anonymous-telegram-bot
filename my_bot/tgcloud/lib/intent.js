// ---------------- تشخیص نیت با امتیازدهی ----------------
// به‌جای "اولین match برنده‌ست"، همه‌ی دسته‌ها امتیاز می‌گیرن و دسته‌ی با بیشترین امتیاز انتخاب می‌شه.
// تطابق کامل کلمه ۲ امتیاز می‌ده، تطابق جزئی (substring) ۱ امتیاز، و برای math وجود عدد/عملگر ۲ امتیاز اضافه می‌ده.
export function detectIntent(text) {
  const t = normalize(text);
  const words = tokenize(t);

  let bestCategory = null;
  let bestScore = 0;

  for (const cat of CATEGORIES) {
    let score = 0;

    for (const kw of cat.keywords) {
      if (kw.includes(' ')) {
        if (t.includes(kw)) score += 2;
      } else if (words.includes(kw)) {
        score += 2;
      } else if (t.includes(kw)) {
        score += 1;
      }
    }

    if (cat.pattern && cat.pattern.test(t)) score += 2;

    if (score > bestScore) {
      bestScore = score;
      bestCategory = cat.name;
    }
  }

  if (bestCategory) return bestCategory;
  if (t.includes('?') || t.includes('؟')) return 'question';
  return 'default';
}

