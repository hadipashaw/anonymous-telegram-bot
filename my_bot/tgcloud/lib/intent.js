// ---------------- NORMALIZER ----------------
export function normalize(text) {
  return text.toLowerCase().replaceAll('ي', 'ی').replaceAll('ك', 'ک').trim();
}

function tokenize(text) {
  return text.split(/[\s.,!؟?؛;:()«»"']+/).filter(Boolean);
}

